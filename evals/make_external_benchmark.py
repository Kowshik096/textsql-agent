"""
make_external_benchmark.py — build a benchmark file from Spider's dev set.

    python evals/fetch_spider.py
    python evals/make_external_benchmark.py --db car_1 --total 25

Writes evals/benchmark_external_<db>.yaml in the same schema as
benchmark.yaml (id / difficulty / question / reference_sql), so the existing
harness scores it unchanged:

    EXTERNAL_DB=evals/external/spider/database/car_1/car_1.sqlite \
        python evals/harness.py --benchmark evals/benchmark_external_car_1.yaml --tag ext

Selection rules, in order:
  - gold SQL must actually execute against the sqlite file and return rows
    (Spider gold includes a few that error on their own database);
  - questions are deduplicated and shuffled with a fixed seed;
  - difficulty is classified from query STRUCTURE - join count, subquery,
    HAVING - never from how hard the question reads;
  - buckets fill easy/medium/hard at roughly 35/35/30 until the total.

The gold queries are taken verbatim: this file deliberately contains zero
hand-written answers. That is the entire point of the external suite.
"""

from __future__ import annotations

import argparse
import json
import random
import sqlite3
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPIDER = ROOT / "evals" / "external" / "spider"

BUCKETS = {"easy": None, "medium": None, "hard": None}
SHARES = (("easy", 0.35), ("medium", 0.35), ("hard", 0.30))


def classify(sql: str) -> str:
    """Structural difficulty. Reads nothing but the shape of the query."""
    s = sql.lower()
    joins = s.count(" join ")
    subquery = s.count("select") > 1
    if joins >= 2 or subquery or "having" in s or "intersect" in s \
            or "except" in s:
        return "hard"
    if joins == 1 or "group by" in s:
        return "medium"
    return "easy"


def executes_with_rows(db_file: Path, sql: str) -> bool:
    try:
        conn = sqlite3.connect(f"{db_file.as_uri()}?mode=ro", uri=True)
        try:
            cur = conn.execute(" ".join(sql.split()))
            rows = cur.fetchmany(5)
        finally:
            conn.close()
    except sqlite3.Error:
        return False
    return len(rows) > 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", required=True,
                    help="Spider db_id, e.g. car_1")
    ap.add_argument("--total", type=int, default=25)
    ap.add_argument("--seed", type=int, default=20260824)
    args = ap.parse_args()

    dev_file = SPIDER / "dev.json"
    db_file = SPIDER / "database" / args.db / f"{args.db}.sqlite"
    if not dev_file.exists() or not db_file.exists():
        print(f"missing {dev_file} or {db_file} - run fetch_spider.py first")
        return 1

    entries = json.loads(dev_file.read_text(encoding="utf-8"))
    candidates = [e for e in entries if e.get("db_id") == args.db]
    print(f"{args.db}: {len(candidates)} candidate pairs")

    seen_questions = set()
    verified = []
    skipped_error = skipped_dupe = 0
    for e in candidates:
        q = e["question"].strip()
        sql = " ".join(e["query"].split())
        if q.lower() in seen_questions:
            skipped_dupe += 1
            continue
        seen_questions.add(q.lower())
        if not executes_with_rows(db_file, sql):
            skipped_error += 1
            continue
        verified.append({"question": q, "reference_sql": sql,
                         "difficulty": classify(sql)})

    rng = random.Random(args.seed)
    rng.shuffle(verified)

    targets = {name: round(args.total * share) for name, share in SHARES}
    picked = {name: [] for name in BUCKETS}
    for case in verified:
        bucket = case["difficulty"]
        if len(picked[bucket]) < targets[bucket]:
            picked[bucket].append(case)
        if sum(len(v) for v in picked.values()) >= args.total:
            break

    cases = []
    n = 0
    for tier in ("easy", "medium", "hard"):
        for case in picked[tier]:
            n += 1
            cases.append({
                "id": f"X{n:03d}",
                "difficulty": tier,
                "question": case["question"],
                "reference_sql": case["reference_sql"],
                "source": f"spider:{args.db}",
                "assumption": "gold SQL verbatim from Spider dev; executed "
                              "and returned rows on its own database",
            })

    out = ROOT / "evals" / f"benchmark_external_{args.db}.yaml"
    header = (
        "# External validation set - generated by make_external_benchmark.py\n"
        f"# spider db_id={args.db} | seed={args.seed} | "
        f"verified={len(verified)} skipped(error)={skipped_error} "
        f"skipped(dup)={skipped_dupe}\n"
        "# Gold SQL is Spider's own; nothing here is hand-written.\n\n"
        "functional:\n\n"
    )
    body = yaml.safe_dump(cases, sort_keys=False, allow_unicode=True,
                          width=100)
    out.write_text(header + body, encoding="utf-8")

    counts = {t: len(picked[t]) for t in BUCKETS}
    print(f"wrote {out.name}: {len(cases)} cases {counts}")
    print("run it:")
    print(f"  EXTERNAL_DB={db_file.relative_to(ROOT)} \\\n"
          f"      python evals/harness.py --benchmark {out.name} --tag ext")
    return 0


if __name__ == "__main__":
    sys.exit(main())
